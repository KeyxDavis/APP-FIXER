create or replace function public.is_school_member(target_school_id text)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
    select exists (
        select 1
        from public.school_memberships
        where school_id = target_school_id
          and user_id = auth.uid()
    );
$$;

create or replace function public.is_school_admin(target_school_id text)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
    select exists (
        select 1
        from public.school_memberships
        where school_id = target_school_id
          and user_id = auth.uid()
          and role in ('admin', 'builder')
    );
$$;

create policy schools_member_read on public.schools
    for select to authenticated
    using (public.is_school_member(id));

create policy memberships_self_read on public.school_memberships
    for select to authenticated
    using (user_id = auth.uid() or public.is_school_admin(school_id));

create policy profiles_self_read on public.user_profiles
    for select to authenticated
    using (user_id = auth.uid() or public.is_school_admin(school_id));
create policy profiles_admin_write on public.user_profiles
    for all to authenticated
    using (public.is_school_admin(school_id))
    with check (public.is_school_admin(school_id));

create policy settings_member_read on public.school_settings
    for select to authenticated
    using (public.is_school_member(school_id));
create policy settings_admin_write on public.school_settings
    for all to authenticated
    using (public.is_school_admin(school_id))
    with check (public.is_school_admin(school_id));

create policy staff_member_read on public.staff
    for select to authenticated
    using (public.is_school_member(school_id));
create policy staff_admin_write on public.staff
    for all to authenticated
    using (public.is_school_admin(school_id))
    with check (public.is_school_admin(school_id));

create policy attendance_member_read on public.attendance
    for select to authenticated
    using (public.is_school_member(school_id));
drop policy if exists attendance_member_write on public.attendance;
drop policy if exists attendance_admin_update on public.attendance;
drop policy if exists attendance_member_exit_update on public.attendance;

create policy activity_member_read on public.activity_logs
    for select to authenticated
    using (public.is_school_member(school_id));
create policy activity_member_insert on public.activity_logs
    for insert to authenticated
    with check (public.is_school_member(school_id));

create policy status_member_read on public.application_status
    for select to authenticated
    using (public.is_school_member(school_id));
create policy status_admin_write on public.application_status
    for all to authenticated
    using (public.is_school_admin(school_id))
    with check (public.is_school_admin(school_id));

